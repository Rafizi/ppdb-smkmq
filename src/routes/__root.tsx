function ErrorComponent({ error, reset }: { error: Error; reset: () => void }) {
  console.error("Application Error:", error);
  const router = useRouter();

  return (
    <div className="flex min-h-screen items-center justify-center bg-background px-4">
      <div className="max-w-md text-center">
        <h1 className="text-xl font-bold tracking-tight text-foreground">
          Terjadi Kendala Memuat Halaman
        </h1>
        <p className="mt-2 text-sm text-muted-foreground">
          Silakan coba muat ulang atau kembali ke halaman utama PPDB.
        </p>
        <div className="mt-6 flex flex-wrap justify-center gap-3">
          <button
            onClick={() => {
              router.invalidate();
              reset();
            }}
            className="inline-flex items-center justify-center rounded-xl bg-primary px-4 py-2 text-sm font-semibold text-primary-foreground transition-colors hover:bg-primary-dark shadow-card"
          >
            Coba Lagi
          </button>
          <a
            href="/"
            className="inline-flex items-center justify-center rounded-xl border border-border bg-card px-4 py-2 text-sm font-semibold text-navy transition-colors hover:bg-cream"
          >
            Ke Beranda
          </a>
        </div>
      </div>
    </div>
  );
}

